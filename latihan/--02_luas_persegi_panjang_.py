# Program: 02_luas_persegi_panjang.py
# Deskripsi: Fungsi menghitung luas persegi panjang menggunakan return.

def luas_persegi_panjang(p, l):
    return p * l

print(luas_persegi_panjang(8, 5))   # Test case 1 -> 40
print(luas_persegi_panjang(2.5, 4)) # Test case 2 -> 10.0
print(luas_persegi_panjang(0, 7))   # Test case 3 -> 0